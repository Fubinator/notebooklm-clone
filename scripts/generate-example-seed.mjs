if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const accountId = process.env.CLOUDFLARE_ACCOUNT_ID;
  const apiToken = process.env.CLOUDFLARE_API_TOKEN;

  if (!accountId || !apiToken) {
    throw new Error(
      "Set CLOUDFLARE_ACCOUNT_ID and CLOUDFLARE_API_TOKEN to regenerate the Example seed.",
    );
  }

  const embeddings = await embedWithCloudflare(
    sources.flatMap((source) => source.passages.map(({ content }) => content)),
    { accountId, apiToken },
  );
  const sql = renderSeed(embeddings);
  const outputPath = fileURLToPath(OUTPUT_URL);
  const temporaryPath = `${outputPath}.${process.pid}.tmp`;

  try {
    await writeFile(temporaryPath, sql, "utf8");
    await rename(temporaryPath, outputPath);
  } catch (error) {
    await unlink(temporaryPath).catch(() => undefined);
    throw error;
  }

  process.stdout.write(`Wrote ${outputPath}\n`);
}

export function renderSeed(embeddings) {
  const passages = sources.flatMap((source) => source.passages);
  if (
    !Array.isArray(embeddings) ||
    embeddings.length !== passages.length ||
    embeddings.some(
      (embedding) =>
        !Array.isArray(embedding) ||
        embedding.length !== DIMENSIONS ||
        embedding.some(
          (value) => typeof value !== "number" || !Number.isFinite(value),
        ),
    )
  ) {
    throw new Error(
      `Expected ${passages.length} finite ${DIMENSIONS}-dimension vectors.`,
    );
  }

  const sql = [];
  sql.push(
    `-- Generated by pnpm seed:example with ${PROVIDER} ${MODEL} (${POOLING} pooling). Do not edit by hand.\n`,
  );
  sql.push(
    `insert into public.notebooks (id, owner_id, is_example, title) values ('${notebook.id}', null, true, ${literal(notebook.title)}) on conflict (id) do update set title = excluded.title;\n`,
  );

  let embeddingIndex = 0;
  for (const [sourceIndex, source] of sources.entries()) {
    const fullContent = source.passages
      .map(({ page, content }) => `[PDF page ${page}]\n${content}`)
      .join("\n\n");
    sql.push(
      `insert into public.sources (id, notebook_id, title, kind, original_url, attribution, license_name, license_url, content, processing_stage, embedding_provider, embedding_model, embedding_dimensions, embedding_pooling) values ('${source.id}', '${notebook.id}', ${literal(source.title)}, 'pdf', ${literal(source.originalUrl)}, ${literal(source.attribution)}, 'NIST Technical Series reuse terms', '${REUSE_TERMS}', ${literal(fullContent)}, 'ready', '${PROVIDER}', '${MODEL}', ${DIMENSIONS}, '${POOLING}') on conflict (id) do update set title = excluded.title, original_url = excluded.original_url, attribution = excluded.attribution, license_name = excluded.license_name, license_url = excluded.license_url, content = excluded.content, processing_stage = excluded.processing_stage, embedding_provider = excluded.embedding_provider, embedding_model = excluded.embedding_model, embedding_dimensions = excluded.embedding_dimensions, embedding_pooling = excluded.embedding_pooling;\n`,
    );

    source.passages.forEach((passage, ordinal) => {
      const sourceNumber = sourceIndex + 1;
      const id = `00000000-0000-4000-8${sourceNumber}00-00000000000${ordinal + 1}`;
      const vector = `[${embeddings[embeddingIndex++].join(",")}]`;
      sql.push(
        `insert into public.passages (id, source_id, ordinal, content, page_number, embedding) values ('${id}', '${source.id}', ${ordinal}, ${literal(passage.content)}, ${passage.page}, '${vector}') on conflict (id) do update set ordinal = excluded.ordinal, content = excluded.content, page_number = excluded.page_number, paragraph_start = null, paragraph_end = null, embedding = excluded.embedding;\n`,
      );
    });
  }

  return sql.join("\n");
}

function literal(value) {
  return `'${value.replaceAll("'", "''")}'`;
}
